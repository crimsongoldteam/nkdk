import {existsSync,readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {yaml} from './candidate-catalog.mjs';

const source='rust/declarations/common/metadata-item-link.yaml';
const lexicon='rust/declarations/common/metadata-path-lexicons.yaml';
const output='rust/declarations/common/type-form-link.generated.yaml';
const literal=value=>({literal:value});
const typeItems={input:'typeItems'};
const sole={one:{in:typeItems,as:'item',where:literal(true)}};
const first={find:{in:typeItems,as:'item',where:literal(true)}};
const itemValue={get:{of:{var:'item'},field:'value'}};
const escapeRegex=value=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');

export function typeFormLinkDeclaration(base,roots) {
  const module=structuredClone(base.declarations.find(item=>item.id==='common.metadata-form-link'));
  if(!module || !roots || Object.keys(roots).length===0)throw new Error('Missing common form link or path-root lexicon');
  module.id='common.type-form-link';
  module.description='Ссылка на форму с сокращением по единственному объектному Тип';
  module.imports.item='common.type-description-item';
  module.inputs.typeItems={type:{kind:'sequence',item:{use:'item',with:{metadataAttributeTypesOnly:true}}}};
  module.types={
    'owner-after-dot':{
      kind:'text-transform',units:'utf16',classes:{separator:[[46,46]]},state:{seen:false},
      transitions:[
        {when:{class:'separator'},emit:'discard',set:{seen:true}},
        {when:{flag:'seen'},emit:'append',set:{}},
        {emit:'discard',set:{}},
      ],
      result:{separator:'',first:{kind:'identity'},rest:{kind:'identity'},lowercase:[],emptyInput:'absent',noTokens:'absent'},
    },
  };
  const rootPattern=spelling=>`^${escapeRegex(spelling)}\\.[A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё0-9_]*$`;
  // A short form without an unambiguous object type must fail the ordinary
  // metadata-name/form checks. Defaults remain scalar so the generic text
  // pattern compiler can prepare them before reading the shortened spelling.
  let rootFromItems=literal('Catalog');
  for(const [root,spelling] of Object.entries(roots).reverse())rootFromItems={
    if:{exists:{in:typeItems,as:'item',where:{matches:{value:itemValue,pattern:rootPattern(spelling)}}}},
    then:literal(root),else:rootFromItems,
  };
  const withSoleItem=value=>({if:sole,then:{match:{value:first,present:{as:'item',then:value},absent:literal('')}},else:literal('')});
  const inferredRoot={if:sole,then:rootFromItems,else:literal('Catalog')};
  const inferredOwner=withSoleItem({
    match:{value:{transform:{local:'owner-after-dot',value:itemValue}},
      present:{as:'ownerName',then:{var:'ownerName'}},absent:literal('')},
  });
  module.representations.yaml={kind:'text-pattern',parts:[
    {optional:'owner',parts:[{field:'root'},{literal:'.'},{field:'owner'},{literal:'.Форма.'}]},
    {field:'form'},
  ]};
  module.presence.unshift(
    {target:{field:'root'},yaml:{missing:{denotes:inferredRoot}}},
    {target:{field:'owner'},yaml:{missing:{denotes:inferredOwner},omitWhen:{and:[
        {eq:[{field:'owner'},inferredOwner]},
        {not:{eq:[inferredOwner,literal('')]}},
        {or:Object.entries(roots).map(([root,spelling])=>({and:[
          {eq:[{field:'root'},literal(root)]},
          {exists:{in:typeItems,as:'item',where:{matches:{value:itemValue,pattern:rootPattern(spelling)}}}},
        ]}))},
      ]}}},
  );
  return module;
}

export function generatedTypeFormLink() {
  const base=yaml.load(readFileSync(source,'utf8'));
  const roots=yaml.load(readFileSync(lexicon,'utf8')).declarations.find(item=>item.id==='common.path-root')?.enum;
  return '# Generated by tools/rules-migration/src/type-form-link-declaration.mjs\n'+
    yaml.dump({format:'nkdk-declarations/1',...typeFormLinkDeclaration(base,roots)},{noRefs:true});
}

if(process.argv[1]===fileURLToPath(import.meta.url)) {
  const content=generatedTypeFormLink();
  if(process.argv.includes('--check')) {
    if(readFileSync(output,'utf8')!==content)throw new Error('Stale type form link declaration');
  } else if(!existsSync(output) || readFileSync(output,'utf8')!==content) {
    writeFileSync(output,content);
  }
}
