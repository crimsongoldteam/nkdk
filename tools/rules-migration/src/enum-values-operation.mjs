import {attachOwnerMembership} from './owner-membership.mjs';
import {existsSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname} from 'node:path';
import {candidateCatalog,yaml} from './candidate-catalog.mjs';
import {enumValueCases} from './enum-value-cases.mjs';

// Publish the researched child boundary through the same automatic source adapter.
// The enclosing enumeration remains a separate acceptance boundary.
const result=enumValueCases(candidateCatalog().catalog);
const modules=result.modules.slice(0,3);
const emission={modules,results:[{ownerRequirements:result.ownerRequirements}]};
attachOwnerMembership(emission);
if(emission.results[0].ownerRequirements)throw new Error('Unmapped owner role');
const previous=modules[2].id;
modules[2].id='metadata.enumeration-values';
for(const item of [...result.cases,...result.factSources])if(item.entry===previous)item.entry=modules[2].id;
const sources=result.cases.flatMap(item=>item.source);
const ownerMembers=JSON.parse(readFileSync('tests/migration/nested-identity-inventory.json','utf8')).rows
  .filter(row=>row.kind==='EnumValue' && sources.some(source=>source.path===row.source))
  .map(row=>{
    if(!sources.some(source=>source.path===row.source && source.sha256===row.sha256))throw new Error('Stale owner membership source');
    return {component:row.component,owner:row.ownerUuid,name:row.name,identity:row.uuid};
  });
const outputs={
  'rust/declarations/objects/enumeration-values.generated.yaml':'# Generated by tools/rules-migration/src/enum-values-operation.mjs\n'+yaml.dump({format:'nkdk-declarations/1',kind:'catalog',declarations:modules},{noRefs:true}),
  'tests/migration/enum-values-operation.json':JSON.stringify({ownerMembers,factSources:result.factSources,cases:result.cases},null,2)+'\n',
};
for(const [path,content] of Object.entries(outputs)) {
  if(process.argv.includes('--check')) {
    if(readFileSync(path,'utf8')!==content)throw new Error('Stale generated operation input: '+path);
  } else if(!existsSync(path) || readFileSync(path,'utf8')!==content) {mkdirSync(dirname(path),{recursive:true});writeFileSync(path,content);}
}
