import {readFileSync,writeFileSync} from 'node:fs';
import {candidateCatalog,yaml} from './candidate-catalog.mjs';
import {loadSources} from './source-snapshot.mjs';
import {elementLinks} from './element-links.mjs';
import {assembleSourceElement} from './source-element-assembly.mjs';

const extraction=JSON.parse(readFileSync('tests/migration/rules-extraction.json','utf8'));
const graph=elementLinks(loadSources(extraction.sourceHashes),extraction.entries);
if(graph.unresolved.length)throw new Error('Unresolved element registrations');
const {catalog}=candidateCatalog();
const declarations=[],assemblies=[];
for(const registration of graph.registrations) {
  const source=extraction.entries.find(entry=>entry.path===registration.item.path && entry.symbol===registration.item.symbol);
  // Singleton registrations refer to this source element's root. Collection
  // elements need their separate source tag/discriminator before this mounting.
  const result=assembleSourceElement(source,registration,catalog,
    {id:'candidate.element.'+registration.type,path:[source.itemType]});
  declarations.push(...result.modules);
  assemblies.push({type:registration.type,entry:result.owner.id,source:registration.item,
    path:[source.itemType],...result.coverage});
}
const outputs=[
  ['rust/declarations/candidates/form-elements.generated.yaml',
    '# Generated by pnpm migration:form-element-assemblies; candidate coverage is not object acceptance.\n'+
    yaml.dump({format:'nkdk-declarations/1',kind:'catalog',declarations},{noRefs:true})],
  ['tests/migration/form-element-assemblies.json',JSON.stringify({
    scope:'Singleton element assembly candidates; relative placement; pending properties remain explicit',assemblies},null,2)+'\n'],
];
for(const [path,text] of outputs) {
  if(process.argv.includes('--check')) {
    if(readFileSync(path,'utf8')!==text)throw new Error('Stale element assembly: '+path);
  } else writeFileSync(path,text);
}
console.log(JSON.stringify({registrations:assemblies.length,declarations:declarations.length,
  complete:assemblies.filter(row=>row.complete).length,pending:assemblies.reduce((sum,row)=>sum+row.pending.length,0)}));
