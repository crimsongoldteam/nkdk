  const files = data.files, production = files.filter(f => f.category === 'production');
  const ruleFiles = production.filter(f => /\/(rules|builders|types)\.ts$/.test(f.path));
  const tests = files.flatMap(f => f.tests);
  const counts = new Map();
  for (const file of ruleFiles) for (const blocker of file.blockers) counts.set(blocker.reason, (counts.get(blocker.reason) ?? 0) + 1);
  const rows = values => values.map(row => `| ${row.join(' | ')} |`).join('\n');
  const samplePaths = [
    'appliedObjects/metadataDocument', 'appliedObjects/metadataDocumentJournal',
    'appliedObjects/metadataWebSocketClient', 'commonObjects/metadataAttribute', 'forms/elements/inputField',
  ];
