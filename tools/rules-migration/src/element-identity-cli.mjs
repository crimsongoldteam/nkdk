import {readFileSync,writeFileSync} from 'node:fs';
import {candidateCatalog,yaml} from './candidate-catalog.mjs';
import {loadSources} from './source-snapshot.mjs';
import {elementLinks} from './element-links.mjs';
import {sourceElementIdentity,sourceElementIdentityFacts} from './source-element-identity.mjs';

const extraction=JSON.parse(readFileSync('tests/migration/rules-extraction.json','utf8'));
const graph=elementLinks(loadSources(extraction.sourceHashes),extraction.entries);
if(graph.unresolved.length || graph.registrations.some(row=>row.blockers.length))
  throw new Error('Unresolved element identity registrations');
const {catalog}=candidateCatalog();
const declarations=graph.registrations.flatMap(registration=>[
  sourceElementIdentity(registration,catalog),
  {...sourceElementIdentityFacts(registration,catalog),kind:'fragment'},
]);
const output='rust/declarations/fragments/form-element-identities.generated.yaml';
const text='# Generated by pnpm migration:form-element-identities; paths are relative to the mounted element.\n'+
  yaml.dump({format:'nkdk-declarations/1',kind:'catalog',declarations},{noRefs:true});
if(process.argv.includes('--check')) {
  if(readFileSync(output,'utf8')!==text)throw new Error('Stale element identity declarations');
} else writeFileSync(output,text);
console.log(JSON.stringify({registrations:graph.registrations.length,declarations:declarations.length,bytes:Buffer.byteLength(text)}));
