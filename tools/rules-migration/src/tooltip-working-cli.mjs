import {readFileSync,writeFileSync} from 'node:fs';
import {candidateCatalog,yaml} from './candidate-catalog.mjs';
import {elementAssemblyCases} from './element-assembly-cases.mjs';
import {workingFamilyOutput} from './working-family-output.mjs';

const declarationPath='rust/declarations/probes/tooltip.generated.yaml';
const framesPath='rust/declarations/probes/tooltip-frames.generated.yaml';
const {catalog}=candidateCatalog({excludePaths:[declarationPath,framesPath]});
const generated=elementAssemblyCases(catalog);
const output=workingFamilyOutput(generated,catalog,{
  scope:'Complete ExtendedTooltip body and inferred parent omission; new identity allocation remains separate',
  rename:module=>module.id.startsWith('migration.element.ExtendedTooltip')?
    module.id.replace('migration.element.ExtendedTooltip','working.element.ExtendedTooltip'):
    module.id.endsWith('.facts')?'working.element.ExtendedTooltip.facts':undefined,
});
const profiles=Object.fromEntries(Object.entries(generated.propertyProfiles).map(([type,profile])=>[
  type,{...profile,declaration:profile.declaration.replace('migration.element.ExtendedTooltip','working.element.ExtendedTooltip')},
]));
// Keep repeated verification placements out of one large rustc unit.
const frames=new Set(['working.element.ExtendedTooltip.frame','working.element.ExtendedTooltip.property.ButtonRules']);
const declarationText=declarations=>'# Generated by pnpm migration:tooltip:working; no hand-written property assembly.\n'+
  yaml.dump({format:'nkdk-declarations/1',kind:'catalog',declarations},{noRefs:true});
for(const [path,text] of [
  ['tools/rules-migration/profiles/declared-elements.json',JSON.stringify(profiles,null,2)+'\n'],
  [declarationPath,declarationText(output.declarations.filter(module=>!frames.has(module.id)))],
  [framesPath,declarationText(output.declarations.filter(module=>frames.has(module.id)))],
  ['tests/migration/tooltip-working.json',JSON.stringify(output.manifest,null,2)+'\n'],
]) {
  if(process.argv.includes('--check')) {
    if(readFileSync(path,'utf8')!==text)throw new Error('Stale working tooltip: '+path);
  } else writeFileSync(path,text);
}
console.log(JSON.stringify({declarations:output.declarations.length,cases:output.manifest.cases.length}));
