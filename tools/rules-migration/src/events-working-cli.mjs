import {readFileSync,writeFileSync} from 'node:fs';
import {candidateCatalog} from './candidate-catalog.mjs';
import {groupedRecordCases} from './grouped-record-cases.mjs';
import {workingFamilyOutput} from './working-family-output.mjs';

// The fixture generator already obtains the form's property contract from the
// checked rules.ts extraction. Reuse that contract, not a handwritten copy.
const declarationPath='rust/declarations/probes/events.generated.yaml';
const {catalog}=candidateCatalog({excludePaths:[declarationPath]});
const generated=groupedRecordCases(catalog);
const cases=generated.cases.filter(row=>row.id.startsWith('event-bindings-'));
const formEntry=cases.find(row=>row.id==='event-bindings-e2e-cf').entry;
const output=workingFamilyOutput({...generated,cases},catalog,{
  scope:'Events contract; whole form and element acceptance remain separate',
  rename:module=>module.kind==='fragment'?'working.events.form-fields':
    module.id==='test.events-owner'?'working.events.collection':
    module.id==='test.absent-events-owner'?'working.events.record':
    module.id===formEntry?'working.events.form':'working.events.element',
});
const outputs=[
  [declarationPath,'# Generated by pnpm migration:events:working; Events projections, not full form acceptance.\n'+
    output.yaml],
  ['tests/migration/events-working.json',JSON.stringify(output.manifest,null,2)+'\n'],
];
for(const [path,text] of outputs) {
  if(process.argv.includes('--check')) {
    if(readFileSync(path,'utf8')!==text)throw new Error('Stale working Events contract: '+path);
  } else writeFileSync(path,text);
}
console.log(JSON.stringify({declarations:output.declarations.length,cases:cases.length}));
