import {readFileSync} from 'node:fs';
import {candidateCatalog} from './candidate-catalog.mjs';
import {selectExecutableFamily,generateExecutableFamily} from './family-check.mjs';
import {commonFamilyOutput} from './common-family-output.mjs';
import {writeChanged} from './focused-output.mjs';

const args=process.argv.slice(2);
const check=args.includes('--check');
const family=selectExecutableFamily(JSON.parse(readFileSync('tests/migration/unified-families.json','utf8')),args.filter(arg=>arg!=='--check'));
if(!/^[a-z0-9-]+$/.test(family))throw new Error('Unsafe family identifier');
const path=`rust/declarations/common/${family}-family.generated.yaml`;
const {catalog}=candidateCatalog({excludePaths:[path]});
const existingIds=new Set(catalog.keys());
const output=commonFamilyOutput(generateExecutableFamily(family,catalog),catalog,{existingIds});
const text='# Generated by common-family-cli; original library names are available to the rules mapper.\n'+output.yaml;
if(check) {
  if(readFileSync(path,'utf8')!==text)throw new Error('Stale common family: '+path);
} else writeChanged(path,text);
console.log(JSON.stringify({family,declarations:output.declarations.length}));
