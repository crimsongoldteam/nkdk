import {existsSync,readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {candidateCatalog,yaml} from './candidate-catalog.mjs';
import {emitBaseCollections} from './base-collection.mjs';
import {loadSources,checkSnapshot} from './source-snapshot.mjs';

export function journalColumnOperation(catalog) {
  const extraction=JSON.parse(readFileSync('tests/migration/rules-extraction.json','utf8'));
  const graph=JSON.parse(readFileSync('tests/migration/collection-links.json','utf8'));
  checkSnapshot(loadSources(extraction.sourceHashes),graph.sourceHashes);
  graph.edges=graph.edges.filter(edge=>edge.item.symbol==='MetadataDocumentJournalColumnRules');
  if(graph.edges.length!==1 || graph.edges[0].owner.symbol!=='MetadataDocumentJournalRules')
    throw new Error('Ambiguous journal column collection');
  const emitted=emitBaseCollections(graph,extraction.entries,catalog,{md:'http://v8.1c.ru/8.3/MDClasses'});
  const [boundary]=emitted.results;
  if(boundary.status!=='candidate')throw new Error(`Journal columns blocked: ${JSON.stringify(boundary.blockers)}`);
  const [row,list]=structuredClone(emitted.modules);
  if(!row || !list || emitted.modules.length!==3)throw new Error('Expected row, list, and owner attachment');
  list.representations.yaml.emptyRowNull=true;
  row.id='metadata.journal-column-row';
  list.imports.item=row.id;
  list.id='metadata.journal-column-rows';
  // The source rules omit the runtime-only base identity. Its XML value is
  // restored from the same project identity index used by other adopted items.
  const baseIds={kind:'index',key:{kind:'record',fields:[
    {name:'component',type:{kind:'scalar',scalar:'text'}},
    {name:'identity',type:{kind:'scalar',scalar:'text'}},
  ]},value:{kind:'scalar',scalar:'text'}};
  const baseLookup={lookup:{in:{input:'baseIds'},key:{record:{component:{input:'component'},identity:{field:'uuid'}}}}};
  row.imports.base='common.string';
  row.value.fields.unshift({name:'internalInfo',type:{use:'base'}});
  row.value.fields.splice(
    row.value.fields.findIndex(field=>field.name==='references'),0,
    {name:'base',type:{use:'base'}},
  );
  row.representations.xml.fields.unshift({field:'internalInfo',path:['md:InternalInfo']});
  row.representations.xml.fields.splice(
    row.representations.xml.fields.findIndex(field=>field.field==='references'),0,
    {field:'base',path:['md:Properties','md:ExtendedConfigurationObject']},
  );
  row.presence.push(
    {target:{field:'internalInfo'},xml:{missing:{denotes:{absent:true}},empty:[{form:'empty-element',denotes:{absent:true}}],canonical:[{when:{eq:[{field:'objectBelonging'},{literal:'Adopted'}]},form:'empty-element'}]},yaml:{missing:{denotes:{absent:true}}}},
    {target:{field:'base'},xml:{missing:{denotes:{absent:true}}},yaml:{missing:{denotes:{if:{present:baseLookup},then:{require:baseLookup},else:{absent:true}}}}},
  );
  const belonging=row.presence.find(item=>item.target.field==='objectBelonging');
  delete belonging.yaml.default;
  belonging.yaml.missing={denotes:{
    if:{present:baseLookup},then:{literal:'Adopted'},else:{literal:'Native'},
  }};
  row.presence.find(item=>item.target.field==='indexing').xml.canonical=[
    {when:{and:[
      {eq:[{field:'objectBelonging'},{literal:'Adopted'}]},
      {eq:[{field:'indexing'},{literal:'DontIndex'}]},
    ]},form:'missing'},
    {form:'ordinary'},
  ];
  row.presence.find(item=>item.target.field==='synonym').xml.canonical=[
    {when:{and:[
      {not:{present:{field:'synonym'}}},
      {eq:[{field:'objectBelonging'},{literal:'Native'}]},
    ]},form:'empty-element'},
    {form:'ordinary'},
  ];
  const synonym=row.value.fields.find(item=>item.name==='synonym');
  synonym.type.bind.ownerName={if:{eq:[{field:'objectBelonging'},{literal:'Adopted'}]},
    then:{literal:''},else:{field:'name'}};
  row.inputs.baseIds={type:baseIds};
  list.inputs.baseIds={type:baseIds};
  list.value.item.bind.baseIds={input:'baseIds'};
  return {modules:[row,list],requirements:boundary.ownerRequirements};
}

if(process.argv[1]===fileURLToPath(import.meta.url)) {
  const {modules}=journalColumnOperation(candidateCatalog().catalog);
  const path='rust/declarations/objects/metadata-journal-column-rows.yaml';
  const content='# Generated by tools/rules-migration/src/journal-column-operation.mjs from rules.ts\n'+
    yaml.dump({format:'nkdk-declarations/1',kind:'catalog',declarations:modules},{noRefs:true});
  if(process.argv.includes('--check')) {
    if(readFileSync(path,'utf8')!==content)throw new Error('Stale journal column collection: '+path);
  } else if(!existsSync(path)||readFileSync(path,'utf8')!==content)writeFileSync(path,content);
}
