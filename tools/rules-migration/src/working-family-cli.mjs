import {readFileSync} from 'node:fs';
import {candidateCatalog} from './candidate-catalog.mjs';
import {selectExecutableFamily,generateExecutableFamily} from './family-check.mjs';
import {workingFamilyOutput} from './working-family-output.mjs';
import {writeChanged} from './focused-output.mjs';

const args=process.argv.slice(2);
const check=args.includes('--check');
const selection=args.filter(arg=>arg!=='--check');
if(selection.length!==2)throw new Error('Usage: migration:working-family --family <id> [--check]');
const family=selectExecutableFamily(JSON.parse(readFileSync('tests/migration/unified-families.json','utf8')),
  selection);
if(!/^[a-z0-9-]+$/.test(family))throw new Error('Unsafe family identifier');
const declarationPath=`rust/declarations/probes/${family}-working.generated.yaml`;
const {catalog}=candidateCatalog({excludePaths:[declarationPath]});
const generated=generateExecutableFamily(family,catalog);
const output=workingFamilyOutput(generated,catalog,{
  scope:`${family}: prepared conversion contracts; production registry acceptance is separate`,
  rename:module=>'working.'+module.id.replace(/^(migration|test|candidate)\./,''),
});
for(const [path,text] of [
  [declarationPath,'# Generated by pnpm migration:working-family; shared contracts are referenced, not copied.\n'+output.yaml],
  [`tests/migration/${family}-working.json`,JSON.stringify(output.manifest,null,2)+'\n'],
]) {
  if(check) {
    if(readFileSync(path,'utf8')!==text)throw new Error(`Stale working family: ${path}`);
  } else writeChanged(path,text);
}
console.log(JSON.stringify({family,declarations:output.declarations.length,cases:output.manifest.cases.length}));
