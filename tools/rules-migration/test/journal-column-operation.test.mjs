import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {candidateCatalog,yaml} from '../src/candidate-catalog.mjs';
import {journalColumnOperation} from '../src/journal-column-operation.mjs';

test('journal column collection is reproducibly generated from the source rules',()=>{
  const {modules,requirements}=journalColumnOperation(candidateCatalog().catalog);
  assert.equal(modules.length,2);
  assert.equal(modules[0].value.fields.find(field=>field.name==='references').type.use,'field5');
  assert.equal(modules[0].imports.field5,'common.metadata-member-links');
  assert.equal(modules[0].value.fields[0].name,'internalInfo');
  assert.equal(modules[0].value.fields.findIndex(field=>field.name==='base')+1,
    modules[0].value.fields.findIndex(field=>field.name==='references'));
  assert.equal(modules[1].value.item.bind.baseIds.input,'baseIds');
  assert.equal(modules[1].representations.yaml.kind,'record-mapping');
  assert.equal(requirements.configurationIndexUidSegment,'Графа');
  const content='# Generated by tools/rules-migration/src/journal-column-operation.mjs from rules.ts\n'+
    yaml.dump({format:'nkdk-declarations/1',kind:'catalog',declarations:modules},{noRefs:true});
  assert.equal(readFileSync('rust/declarations/objects/metadata-journal-column-rows.yaml','utf8'),content);
});
