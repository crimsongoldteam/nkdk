import { mergeInputs } from '../src/common-inputs.mjs';
import { ownerContext } from '../src/fixture-context.mjs';
import { propertyContract } from '../src/property-contract.mjs';
import { createHash } from 'node:crypto';
import { i8nContracts } from '../src/i8n-contracts.mjs';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { literalTables, booleanExpectations, literalFixture } from '../src/test-cases.mjs';

test('test data extraction keeps literal expectations independent and reports dynamic rows', () => {
  const source = `it.each([["<Value>42</Value>",42],["<Value/>",undefined]])('values',(xml,expected)=>{
    expect(convert(xml)).toEqual(expected);
  }); it.each(runtime())('dynamic',x=>expect(convert(x)).toEqual(x));`;
  const result = literalTables('cases.ts',source);
  assert.equal(result.tables[0].rows[0][1],42);
  assert.deepEqual(result.tables[0].rows[1][1],{$undefined:true});
  assert.equal(result.pending.length,1);
  assert.equal(result.tables[0].source.line,1);
  const fixtures = literalFixture('fixture.ts','export const samples = [{xml: "<A/>", expected: "independent"}];','samples');
  assert.equal(fixtures.data[0].expected,'independent');
  assert.throws(() => literalFixture('fixture.ts','const samples = dynamic();','samples'), /Nonliteral/);
  assert.equal(literalFixture('hint.ts','const hint = "Text"; const samples = `Known ${hint}: ${38}`;','samples').data,'Known Text: 38');
  assert.throws(()=>literalFixture('hint.ts','const samples = `Unknown ${runtime()}`;','samples'),/Nonliteral/);
  assert.throws(()=>literalFixture('hint.ts','const samples = `Object ${{name:"x"}}`;','samples'),/Nonliteral/);
  const boolean = booleanExpectations('boolean.ts','const result = importBooleanFromXML(ctx, rule, "true"); expect(result).toBe(true);');
  assert.equal(boolean[0].input,'true');
  assert.equal(boolean[0].expected,true);
  const context=ownerContext({roots:[{source:'root.xml',kind:'ExternalDataSource',name:'Source',identity:'root'}],children:[{source:'table.xml',kind:'Table',name:'TableName',identity:'table',parent:'root'}],forms:[{source:'form.xml',name:'List',parent:'table'}]},'table.xml','TableName');
  assert.deepEqual(context.values,{owner:'ExternalDataSource.Source.Table.TableName',forms:['List']});
  assert.equal(context.sources.length,3);
  assert.throws(()=>ownerContext({roots:[],children:[],forms:[]},'missing.xml','Missing'),/Ambiguous owner/);
  const fragment={format:'nkdk-declarations/1',kind:'fragment',id:'fields',imports:{text:'common.string'},value:{kind:'record',fields:[{name:'one',type:{use:'text'}},{name:'two',type:{use:'text'}}]},representations:{xml:{kind:'record',fields:[{field:'one',path:['Root','One']},{field:'two',path:['Root','Two']}]},yaml:{kind:'mapping',fields:[{field:'one',key:'First'},{field:'two',key:'Second'}]}},presence:[{target:{field:'one'},yaml:{default:{literal:''}}}]};
  const projected=propertyContract({id:'owner',fragments:['fields']},'one',new Map([['fields',fragment]]));
  assert.equal(projected.module.kind,'object');assert.equal(projected.module.value.fields.length,1);
  assert.equal(fragment.value.fields.length,2);
  assert.equal(projected.module.presence[0].yaml.default.literal,'');
  assert.equal(projected.source.sourceFragment,'fields');
  const wrapped=propertyContract({id:'owner',fragments:['fields']},'one',new Map([['fields',fragment]]),'Envelope');
  assert.deepEqual(wrapped.module.representations.xml.fields[0].path,['Envelope','Root','One']);
  assert.notEqual(wrapped.module.id,projected.module.id);
  assert.deepEqual(fragment.representations.xml.fields[0].path,['Root','One']);
  assert.throws(()=>propertyContract({id:'owner',fragments:['fields']},'one',new Map([['fields',fragment]]),'Bad/Path'),/Invalid property container/);
  const inputs={context:{type:{kind:'scalar',scalar:'text'}}};
  assert.doesNotThrow(()=>mergeInputs(inputs,structuredClone(inputs)));
  assert.throws(()=>mergeInputs(inputs,{context:{type:{kind:'scalar',scalar:'boolean'}}}),/Conflicting input/);
  const dependent=structuredClone(fragment);dependent.presence[0].yaml.default={field:'two'};
  assert.throws(()=>propertyContract({id:'owner',fragments:['fields']},'one',new Map([['fields',dependent]])),/Cross-property/);
  const constrained=structuredClone(fragment);
  constrained.constraints=['one','two'].map(field=>({id:field,assert:{present:{field}},diagnostic:{at:{field}}}));
  assert.deepEqual(propertyContract({id:'owner',fragments:['fields']},'one',new Map([['fields',constrained]])).module.constraints,[constrained.constraints[0]]);
  constrained.constraints[0].assert={eq:[{field:'one'},{field:'two'}]};
  assert.throws(()=>propertyContract({id:'owner',fragments:['fields']},'one',new Map([['fields',constrained]])),/Cross-property/);
  constrained.constraints=[{assert:{literal:true}}];
  assert.throws(()=>propertyContract({id:'owner',fragments:['fields']},'one',new Map([['fields',constrained]])),/Unscoped constraint/);
  const xml='<Root><Title/></Root>';
  const observation={profile:0,case:'empty-container',sourceXML:xml,sourceSha256:createHash('sha256').update(xml).digest('hex'),yaml:'Title: !xml/raw\n  $xml:',parameters:{typedXML:false}};
  const converted=i8nContracts({rows:[observation]},'candidate');
  assert.equal(converted[0].yaml,'Title: !xml/raw\n  $xml: ""');
  assert.equal(converted[0].entry,'candidate');
  assert.equal(Object.hasOwn(converted[0].inputs,'ownerName'),false);
  const named=i8nContracts({rows:[{...observation,profile:2,name:'TestName',parameters:{excludeIfEqualNameYAML:true}}]},'candidate',2);
  assert.equal(named[0].inputs.ownerName,'TestName');
  assert(named[0].xml.startsWith('<Properties'));
  assert.throws(()=>i8nContracts({rows:[]},'candidate',8),/Unsupported candidate profile/);
  assert(!converted[0].xml.includes('<Root>'));
  assert.throws(()=>i8nContracts({rows:[{...observation,sourceXML:'<Other/>'}]},'candidate'),/Changed XML/);
  assert.throws(()=>i8nContracts({rows:[{...observation,parameters:{typedXML:true}}]},'candidate'),/Unsupported observation/);
});
