import {test} from 'node:test';
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {yaml} from '../src/candidate-catalog.mjs';

test('document attribute operation publishes its source-derived declarations and e2e case',()=>{
  execFileSync(process.execPath,['tools/rules-migration/src/document-attributes-operation.mjs','--check'],{stdio:'pipe'});
  const catalog=yaml.load(readFileSync('rust/declarations/candidates/document-attributes.generated.yaml','utf8'));
  const owner=catalog.declarations.find(module=>module.id==='metadata.document-attributes');
  const fragment=catalog.declarations.find(module=>module.id==='fragment.document-attributes');
  const fields=catalog.declarations.find(module=>module.id==='fragment.document-owner-properties');
  const joined=catalog.declarations.find(module=>module.id==='migration.document-attribute-form-links');
  assert.ok(owner);
  assert.ok(joined);
  assert.deepEqual(joined.compose.map(part=>part.use),['ownerProperties','attributes']);
  assert.deepEqual(fields.representations.xml.fields.at(-1).path,['md:MetaDataObject','md:Document','md:Properties','md:DataLockFields']);
  assert.equal(fields.imports.value1,'common.owner-metadata-fields');
  assert.deepEqual(fragment.representations.xml.fields[0].path,['md:MetaDataObject','md:Document','md:ChildObjects']);
  const cases=JSON.parse(readFileSync('tests/migration/document-attributes-operation.json','utf8'));
  assert.equal(cases.cases.length,18);
  assert(cases.cases.every(item=>Array.isArray(item.factSourceEntries)&&item.factSourceEntries.length));
  assert.equal(cases.cases[0].entry,owner.id);
  assert.equal(cases.cases[1].entry,joined.id);
  assert.equal(cases.cases[2].entry,joined.id);
  assert.match(cases.cases[2].id,/cfe$/);
  const pathCheck=cases.cases.find(item=>item.id==='e2e-document-attribute-metadata-path');
  assert.equal(pathCheck.factBindings.pathChildren,'metadata.path-children');
  assert(pathCheck.rejectedYAML.some(value=>value.includes('НеСуществует')));
  const commandCheck=cases.cases.find(item=>item.id==='e2e-document-command-metadata-path');
  assert.equal(commandCheck.factBindings.pathChildren,'metadata.path-children');
  assert(commandCheck.xml.includes('Command.Команда1'));
  assert(commandCheck.rejectedYAML.some(value=>value.includes('НеСуществует')));
  assert(cases.factSources.some(item=>item.entry==='migration.document-commands'));
  const nested=cases.cases.find(item=>item.id==='e2e-document-tabular-section-attributes-cf');
  assert(nested.xml.includes('РеквизитТабличнойЧасти'));
  assert(nested.yaml.includes('РеквизитТабличнойЧасти:'));
  assert(cases.factSources.some(item=>item.entry===nested.entry));
  const internal=cases.cases.find(item=>item.id==='e2e-document-tabular-section-internal-info-cf');
  assert(internal.xml.includes('DocumentTabularSectionRow.ДокументВсеСвойства.ТабличнаяЧасть'));
  assert.equal(internal.inputs.name,'ДокументВсеСвойства.ТабличнаяЧасть');
  const whole=cases.cases.find(item=>item.id==='e2e-document-tabular-section-whole-cf');
  assert(whole.xml.includes('РеквизитТабличнойЧасти'));
  assert(whole.yaml.includes('Реквизиты:'));
  assert(catalog.declarations.some(module=>module.id===whole.entry));
  const collection=cases.cases.find(item=>item.id==='e2e-document-tabular-sections-collection-cf');
  assert(collection.xml.includes('ChildObjects'));
  assert(collection.yaml.includes('ТабличныеЧасти:'));
  assert(!collection.factSourceEntries.includes(nested.entry),
    'the collection must prepare nested attribute UUIDs from its own rows');
  const projection=catalog.declarations.find(module=>module.id===collection.entry);
  const sequence=catalog.declarations.find(module=>module.id===projection.imports.items);
  const item=catalog.declarations.find(module=>module.id===sequence.imports.item);
  assert.equal(sequence.representations.yaml.kind,'record-mapping');
  assert.equal(item.kind,'value');
  assert(item.compose.length>=4);
  const combined=cases.cases.find(item=>item.id==='e2e-document-attributes-and-tabular-sections-cf');
  assert(combined.xml.includes('TabularSection uuid='));
  assert(combined.xml.includes('Attribute uuid='));
  assert(combined.xml.includes('<ns0:Characteristics>'));
  assert(combined.xml.includes('<ns0:StandardAttributes>'));
  assert(combined.yaml.includes('Характеристики:'));
  assert(combined.yaml.includes('СтандартныеРеквизиты:'));
  assert(combined.yaml.includes('ТабличныеЧасти:'));
  assert(!combined.factSourceEntries.includes(nested.entry));
  const combinedOwner=catalog.declarations.find(module=>module.id===combined.entry);
  assert(combinedOwner.compose.some(part=>part.use==='baseProperties'));
  assert(combinedOwner.compose.some(part=>part.use==='tabularSections'));
  assert(combinedOwner.compose.some(part=>part.use==='characteristics'));
  assert(combinedOwner.compose.some(part=>part.use==='objectBelonging'));
  assert(combinedOwner.compose.some(part=>part.use==='standardAttributes'));
  const inputByString=cases.cases.find(item=>item.id==='e2e-document-input-by-string-cf');
  assert.ok(inputByString);
  assert.equal(inputByString.entry,'migration.document-input-by-string-probe');
  const inputByStringOwner=catalog.declarations.find(module=>module.id===inputByString.entry);
  assert.equal(inputByStringOwner.imports.part,'fragment.document-input-by-string-probe');
  const inputByStringFragment=catalog.declarations.find(module=>module.id===inputByStringOwner.imports.part);
  assert.deepEqual(inputByStringFragment.value.fields.map(field=>field.name),['history','NumberType','NumberLength','InputByString']);
  assert(inputByString.xml.includes('<ns0:InputByString>'));
  assert(inputByString.yaml.includes('ВводПоСтроке:'));
  assert(inputByString.yaml.includes('СтандартныйРеквизит.Номер'));
  assert.equal(inputByString.factBindings?.members,'metadata.input-by-string-members');
  assert.equal(inputByStringFragment.imports.fields,'common.owner-checked-metadata-fields');
  const checkedBase=catalog.declarations.find(module=>module.id===combinedOwner.imports.baseProperties);
  assert.equal(checkedBase.imports.fields,'common.owner-checked-metadata-fields');
  assert.equal(combined.factBindings?.inputByStringMembers,'metadata.input-by-string-members');
  assert.equal(combined.factBindings?.propertyStates,'metadata.property-state-membership');
  assert.equal(inputByStringFragment.imports.number,'common.stateful-number');
  assert(combined.rejectedYAML.some(value=>value.includes('Реквизит.ПолныйРеквизит')));

  const inputByStringDefault=cases.cases.find(item=>item.id==='e2e-document-input-by-string-default-cf');
  assert.equal(inputByStringDefault.yaml,'ДлинаНомера: 11\n');
  assert.equal(inputByStringDefault.rejectedCode,'yaml.implicit-value');
  const inputByStringZero=cases.cases.find(item=>item.id==='e2e-document-input-by-string-zero-cf');
  assert.equal(inputByStringZero.yaml,'ДлинаНомера: 0\n');
  assert.equal(inputByStringZero.rejectedCode,'yaml.implicit-value');
  const standards=cases.cases.find(item=>item.id==='e2e-tabular-section-standard-attributes-catalog-cf');
  assert(standards.xml.includes('StandardAttribute name="LineNumber"'));
  assert(standards.yaml.includes('НомерСтроки:'));
  const catalogWhole=cases.cases.find(item=>item.id==='e2e-catalog-tabular-section-whole-cf');
  assert(catalogWhole.xml.includes('ТабличнаяЧастьПолный'));
  assert(catalogWhole.yaml.includes('Использование:'));
  assert(catalogWhole.yaml.includes('НомерСтроки:'));
  const emptySynonym=cases.cases.find(item=>item.id==='e2e-catalog-tabular-section-empty-synonym-cf');
  assert(emptySynonym.xml.includes('<ns0:Synonym/>'));
  assert(emptySynonym.yaml.includes('Синоним: ""'));
  assert.equal(emptySynonym.entry,catalogWhole.entry);
  const invalidLength=cases.cases.find(item=>item.id==='e2e-catalog-tabular-section-invalid-line-length-cf');
  assert(invalidLength.xml.includes('<ns0:LineNumberLength>bad</ns0:LineNumberLength>'));
  assert(invalidLength.yaml.includes('LineNumberLength: !xml/raw'));
  assert(invalidLength.yaml.includes('"#text": bad'));
  assert(invalidLength.retainedYAML.includes('Комментарий: Комментарий'));
  const catalogCollection=cases.cases.find(item=>item.id==='e2e-catalog-tabular-sections-collection-cf');
  assert(catalogCollection.xml.includes('ChildObjects'));
  assert(catalogCollection.xml.includes('ТабличнаяЧастьМинимальный'));
  assert(catalogCollection.xml.includes('ТабличнаяЧастьПолный'));
  assert(catalogCollection.yaml.includes('ТабличныеЧасти:'));
  assert.equal(catalogCollection.factSourceEntries[0],catalogCollection.entry);
  assert(catalogCollection.factSourceEntries.includes('migration.catalog-minimal-internal-types'));
  assert(cases.factSources.some(item=>item.entry==='metadata.document-attributes'));
  assert.equal(owner.contributions.some(item=>item.index==='metadata.owner-members'),true);
  assert.equal(cases.requirements.owner.operationTarget.kind,'namedCollectionTarget');
});
