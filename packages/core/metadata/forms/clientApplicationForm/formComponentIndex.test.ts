import { describe, expect, it } from "vitest"
import { indexClientApplicationFormComponents } from "./formComponentIndex"

describe("индекс компонентов формы", () => {
  it("индексирует все категории и рекурсивные элементы с YAML-путями", () => {
    const index = indexClientApplicationFormComponents({
      КоманднаяПанель: {
        Элементы: {
          ГлавнаяКнопка: { Вид: "КнопкаКоманднойПанели", ТипКнопки: "КнопкаКоманднойПанели" },
        },
      },
      Элементы: {
        Группа: { Вид: "Группа", Элементы: { Поле: { Вид: "ПолеВвода" } } },
        Товары: {
          Вид: "ТаблицаФормы",
          КоманднаяПанель: {
            Элементы: {
              Добавить: { Вид: "КнопкаКоманднойПанели", ТипКнопки: "КнопкаКоманднойПанели" },
            },
          },
          КонтекстноеМеню: {
            Элементы: {
              Удалить: { Вид: "КнопкаКоманднойПанели", ТипКнопки: "КнопкаКоманднойПанели" },
            },
          },
        },
      },
      Реквизиты: { Объект: {} },
      Команды: { Записать: {} },
      Параметры: { Режим: {} },
    })

    expect([...index.elements.values()]).toEqual(expect.arrayContaining([
      { name: "Группа", path: "Элементы.Группа" },
      { name: "Поле", path: "Элементы.Группа.Элементы.Поле" },
      { name: "Товары", path: "Элементы.Товары" },
      { name: "Добавить", path: "Элементы.Товары.КоманднаяПанель.Элементы.Добавить" },
      { name: "Удалить", path: "Элементы.Товары.КонтекстноеМеню.Элементы.Удалить" },
      { name: "ГлавнаяКнопка", path: "КоманднаяПанель.Элементы.ГлавнаяКнопка" },
    ]))
    expect(index.elements.size).toBe(6)
    expect(index.attributes.get("Объект")?.path).toBe("Реквизиты.Объект")
    expect(index.commands.get("Записать")?.path).toBe("Команды.Записать")
    expect(index.parameters.get("Режим")?.path).toBe("Параметры.Режим")
  })

  it("запрещает повтор имени элемента во всём дереве", () => {
    expect(() => indexClientApplicationFormComponents({
      КоманднаяПанель: {
        Элементы: { Поле: { Вид: "КнопкаКоманднойПанели", ТипКнопки: "КнопкаКоманднойПанели" } },
      },
      Элементы: { Поле: { Вид: "ПолеВвода" } },
    })).toThrow("Повтор имени элемента «Поле»")
  })
})
